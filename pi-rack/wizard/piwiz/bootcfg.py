# Note: the node identity file (/etc/pi-rack.env) is contributed by roles.py, so
# that it is written from the same data the role scripts are given. There is
# deliberately only one identity file - two would drift.

BASE_RUNCMD: list[str] = [
    # Prove the seed actually ran. If this file is missing after a boot, cloud-init
    # did not execute - which is a completely different problem from "the service
    # failed", and knowing which saves an hour.
    "[ sh, -c, \"date -Is > /var/lib/pi-rack-provisioned\" ]",
]


def validate(text: str, what: str) -> None:
    """Parse the rendered YAML back. A silent syntax error here means a Pi that
    boots to a login prompt with no user, no network and no SSH - i.e. a node you
    have to physically retrieve. Worth the check."""
    if _yaml is None:
        return
    try:
        _yaml.safe_load(text)
    except Exception as exc:  # pragma: no cover
        raise BootConfigError(f"{what} is not valid YAML: {exc}") from exc


_DS_RE = re.compile(r"ds=nocloud[^\s]*")


def reconcile_cmdline(boot_dir: Path, iid: str) -> bool:
    """Make `cmdline.txt` agree with our meta-data, or get out of the way.

    Raspberry Pi Imager appends ` ds=nocloud;i=<its own id>` to cmdline.txt when
    it writes a cloud-init seed. A kernel-cmdline instance id **overrides** the
    one in meta-data, and that quietly breaks the most useful property of this
    wizard: edit fleet.toml, re-seed the card, and have cloud-init genuinely
    re-provision. With a stale `i=` still on the cmdline, cloud-init decides it
    has seen this instance before and skips first-boot setup - and you get a node
    that boots with none of your changes and no error anywhere.

    So: if the parameter is there, rewrite its id to ours. If it is absent, leave
    it absent - the image's own `datasource_list: [NoCloud, None]` with
    `seedfrom: file:///boot/firmware` already finds the seed without it.

    Returns True if the file was changed.

    `cmdline.txt` MUST stay a single line. The bootloader reads line one and
    silently ignores anything after it, so a stray newline here removes every
    parameter that follows - a failure with no error message at all.
    """
    path = Path(boot_dir) / "cmdline.txt"
    if not path.exists():
        return False

    raw = path.read_text(encoding="utf-8")
    line = raw.strip().splitlines()[0] if raw.strip() else ""
    if "ds=nocloud" not in line:
        return False

    new_line = _DS_RE.sub(f"ds=nocloud;i={iid}", line, count=1)
    new_line = " ".join(new_line.split())
    if new_line == line:
        return False

    path.write_text(new_line + "\n", encoding="utf-8", newline="\n")
    return True


def write_seed(
    boot_dir: Path,
    fleet: Fleet,
    node: Node,
    bundle: RoleBundle | None = None,
    *,
    plan_revision: str = "",
    package_upgrade: bool = False,
) -> list[Path]:
    """Write user-data, network-config and meta-data into a mounted bootfs.

    `boot_dir` must be the root of the FAT32 boot partition, i.e. the drive
    Windows mounted after the image was written. This function refuses to write
    anywhere that does not look like one, because pointing it at the wrong
    directory would scatter three files into a real filesystem.
    """
    boot_dir = Path(boot_dir)
    if not boot_dir.is_dir():
        raise BootConfigError(f"{boot_dir} is not a directory")
    if not (boot_dir / "config.txt").exists() or not (boot_dir / "cmdline.txt").exists():
        raise BootConfigError(
            f"{boot_dir} does not look like a Raspberry Pi boot partition "
            "(no config.txt / cmdline.txt). Refusing to write seed files there."
        )

    reconcile_cmdline(boot_dir, instance_id(node, plan_revision))

    rendered = {
        "meta-data": render_meta_data(node, plan_revision),
        "network-config": render_network_config(fleet, node),
        "user-data": render_user_data(
            fleet, node, bundle, package_upgrade=package_upgrade
        ),
    }
    for name, text in rendered.items():
        validate(text, name)

    written: list[Path] = []
    for name, text in rendered.items():
        target = boot_dir / name
        # newline="\n": these are read by a Linux boot process. CRLF in cmdline.txt
        # is a classic Pi failure and there is no reason to risk it here.
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written

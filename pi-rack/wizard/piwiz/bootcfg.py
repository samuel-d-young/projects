"""Render the three cloud-init seed files that go on a Pi's boot partition.

GROUND TRUTH (verified 2026-08-28 by extracting the official image
`2026-06-18-raspios-trixie-arm64-lite.img.xz`, sha256 e235fd24...c33a9, and
reading `/etc/cloud/cloud.cfg` and `/etc/cloud/cloud.cfg.d/99_raspberry-pi.cfg`
out of its root filesystem):

  * Raspberry Pi OS trixie configures cloud-init with
    `datasource_list: [ NoCloud, None ]` and `seedfrom: file:///boot/firmware`.
    So the seed files are `user-data`, `network-config` and `meta-data`, sitting
    in the root of the FAT32 `bootfs` partition - the one Windows mounts.
  * This is NOT the old `custom.toml` mechanism and NOT `firstrun.sh`. Guidance
    written for Bookworm and earlier will tell you otherwise; it is out of date.
    The image's own `os_list_imagingutility_v4.json` entry declares
    `init_format = "cloudinit-rpi"`, which is the machine-readable version of
    this same fact.
  * The default user is `pi` with `lock_passwd: true` and NOPASSWD sudo. It is
    created BY cloud-init, not baked into the image - so a `users:` block that
    omits `default` means the `pi` user is never created at all. That is how
    this module removes it: by never asking for it.
  * `preserve_hostname: false`, so `hostname:` in user-data is honoured.
  * Host keys are generated by `regenerate_ssh_host_keys.service` on first boot
    (`ssh_genkeytypes: []`, `ssh_deletekeys: false`), so flashing the same image
    to five cards does NOT give five Pis the same host key.
  * `meta-data.instance_id` is compared against a cached copy; changing it makes
    cloud-init believe it is on a new instance and re-run first-boot setup. Each
    node therefore gets its own instance_id, stamped with the plan revision.
  * Network renderers are `['netplan', 'network-manager']`, so `network-config`
    is netplan v2 and gets applied through NetworkManager.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

from .fleet import Fleet, Node

try:  # optional - used only to prove what we emit parses back
    import yaml as _yaml
except ImportError:  # pragma: no cover
    _yaml = None


class BootConfigError(RuntimeError):
    pass


@dataclass
class RoleBundle:
    """Everything the selected roles contribute to one node's first boot."""

    packages: list[str] = field(default_factory=list)
    write_files: list[tuple[str, str, str]] = field(default_factory=list)  # path, content, mode
    runcmd: list[str] = field(default_factory=list)
    summary: str = ""


# --- YAML emission ---------------------------------------------------------------
# Hand-rolled rather than PyYAML, for two reasons: the output stays commented and
# diff-friendly (these files get read by a human at 1am with a card reader in one
# hand), and the wizard keeps its stdlib-only footprint. PyYAML, when present, is
# used to prove the result parses - see validate().


def _q(value: str) -> str:
    """Quote a scalar for YAML. Always quotes, so nothing is ever reinterpreted
    as a bool, a number, a date, or None - the classic YAML foot-guns."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _block(content: str, indent: int) -> str:
    """A literal block scalar, indented. Trailing whitespace is stripped per line
    because YAML block scalars preserve it and shells do not appreciate it."""
    pad = " " * indent
    lines = [pad + line.rstrip() for line in content.splitlines()]
    return "\n".join(lines)


def instance_id(node: Node, plan_revision: str = "") -> str:
    """Stable per node, but changes when the plan changes.

    Deliberate: re-running the wizard after editing fleet.toml should make
    cloud-init treat the card as a new instance and redo first-boot setup,
    rather than silently no-op because it has seen `rpios-image` before.
    """
    digest = hashlib.sha256(
        f"{node.hostname}|{node.ip}|{','.join(sorted(node.roles))}|{plan_revision}".encode()
    ).hexdigest()[:12]
    return f"pi-rack-{node.hostname}-{digest}"


def render_meta_data(node: Node, plan_revision: str = "") -> str:
    iid = instance_id(node, plan_revision)
    return f"""# cloud-init meta-data - generated by piwiz, do not hand-edit.
# Node: {node.hostname} ({node.hardware}) at {node.ip}
#
# dsmode: local means user-data is acted on BEFORE the network comes up, which
# is what we want - the network config itself is part of the seed.
dsmode: local

# BOTH spellings on purpose. cloud-init's canonical NoCloud key is `instance-id`
# (hyphen) and that is what Raspberry Pi Imager writes; the meta-data shipped
# inside the Raspberry Pi OS image spells it `instance_id` (underscore). Rather
# than bet on which one is read, emit both with the same value - the unused one
# is ignored, and there is no version of this where we get the wrong id.
#
# Changing it makes cloud-init treat this as a brand new machine and re-run
# first-boot setup. It is derived from the node's plan entry, so editing
# fleet.toml and re-flashing genuinely re-provisions instead of silently no-oping.
instance-id: {iid}
instance_id: {iid}

# Used for the hostname when no `hostname:` is set in user-data. We always set
# one, but this keeps the two consistent if user-data is ever trimmed.
local-hostname: {node.hostname}
"""


def render_network_config(fleet: Fleet, node: Node) -> str:
    """Static IPv4 on eth0, netplan v2.

    `optional: false` is deliberate and load-bearing: it makes systemd wait for
    the link before cloud-init's later stages run. Every node here installs
    packages on first boot, and on a fast Pi 5 cloud-init will otherwise start
    apt before the link is up and fail the whole run.
    """
    dns = ", ".join(fleet.network.dns)
    prefix = fleet.network.cidr.prefixlen
    return f"""# cloud-init network-config (netplan v2) - generated by piwiz.
# Node: {node.hostname} -> {node.ip}/{prefix}
#
# Whitespace-sensitive YAML. Spaces only, never tabs.
#
# This is applied ONCE, on first boot. Changing it later means either
# re-flashing or editing /etc/netplan on the running node.
network:
  version: 2
  ethernets:
    eth0:
      dhcp4: false
      dhcp6: false
      # false = boot waits for this link. Required: first boot installs packages.
      optional: false
      addresses:
        - {node.ip}/{prefix}
      routes:
        - to: default
          via: {fleet.network.gateway}
      nameservers:
        addresses: [{dns}]
        search: [{fleet.network.domain}]
"""


def render_user_data(
    fleet: Fleet,
    node: Node,
    bundle: RoleBundle | None = None,
    *,
    package_upgrade: bool = False,
) -> str:
    bundle = bundle or RoleBundle()

    pubkey = fleet.ssh_pubkey_path.read_text(encoding="utf-8").strip()
    # Order matters: pointing at the private key instead of the .pub is the
    # common mistake, so it has to be checked before the generic shape test -
    # otherwise it is reported as "not a public key", which is true but unhelpful.
    if "PRIVATE KEY" in pubkey.upper():
        raise BootConfigError(
            f"{fleet.ssh_pubkey_path} is a PRIVATE key. "
            f"Point ssh_pubkey_path at {fleet.ssh_pubkey_path}.pub instead - and "
            "note that this private key has now been read by a tool, so consider "
            "whether it belongs somewhere more protected."
        )
    if not pubkey.startswith(("ssh-ed25519", "ssh-rsa", "ecdsa-sha2")):
        raise BootConfigError(
            f"{fleet.ssh_pubkey_path} does not look like an SSH public key "
            "(expected a line starting ssh-ed25519, ssh-rsa or ecdsa-sha2)"
        )

    packages = sorted(set(BASE_PACKAGES + list(bundle.packages)))

    out: list[str] = []
    add = out.append

    add("#cloud-config")
    add("# Generated by piwiz - do not hand-edit; edit fleet.toml and re-render.")
    add(f"# Node: {node.hostname}  {node.hardware}  {node.ip}")
    add(f"# Roles: {', '.join(node.roles) or '(none)'}")
    if bundle.summary:
        for line in bundle.summary.splitlines():
            add(f"# {line}")
    add("")

    add(f"hostname: {node.hostname}")
    add("prefer_fqdn_over_hostname: false")
    add("manage_etc_hosts: true")
    add("")

    add(f"timezone: {fleet.timezone}")
    add(f"locale: {fleet.locale}")
    add("keyboard:")
    add(f"  layout: {fleet.keyboard}")
    add("")

    add("# No `- default` entry here, and that is the point: on Raspberry Pi OS the")
    add("# `pi` user is created BY cloud-init from system_info.default_user. Omitting")
    add("# `default` means it is never created, so there is no stock account to attack.")
    add("users:")
    add(f"  - name: {fleet.admin_user}")
    add("    gecos: pi-rack admin")
    add("    shell: /bin/bash")
    add("    sudo: \"ALL=(ALL) NOPASSWD:ALL\"")
    add("    groups: [adm, dialout, cdrom, audio, users, sudo, video, games, plugdev, input, gpio, spi, i2c, netdev, render]")
    add("    # No password at all. The only way in is the key below.")
    add("    lock_passwd: true")
    add("    ssh_authorized_keys:")
    add(f"      - {_q(pubkey)}")
    add("")

    add("# Key-only SSH. Combined with lock_passwd above there is no password path in.")
    add("ssh_pwauth: false")
    add("disable_root: true")
    add("")

    add("package_update: true")
    add(f"package_upgrade: {'true' if package_upgrade else 'false'}")
    if package_upgrade:
        add("# NOTE: a full upgrade on first boot can add 5-15 minutes before the node")
        add("#       is reachable, and on a slow card it looks exactly like a failed flash.")
    add("packages:")
    for pkg in packages:
        add(f"  - {pkg}")
    add("")

    files = list(BASE_WRITE_FILES) + list(bundle.write_files)
    if files:
        add("write_files:")
        for path, content, mode in files:
            add(f"  - path: {path}")
            add(f"    permissions: {_q(mode)}")
            add("    owner: root:root")
            add("    content: |")
            add(_block(content, 6))
        add("")

    runcmd = list(bundle.runcmd) + list(BASE_RUNCMD)
    if runcmd:
        add("runcmd:")
        for cmd in runcmd:
            add(f"  - {cmd}")
        add("")

    add(f"final_message: \"pi-rack: {node.hostname} up after $UPTIME seconds, cloud-init $VERSION\"")
    add("")

    return "\n".join(out)


# Installed on every node regardless of role. Kept short on purpose: anything
# role-specific belongs in that role, not here.
